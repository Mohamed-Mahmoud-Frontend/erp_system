type SaveError = { code?: string; message?: string };

export function payrollSaveError(error: SaveError): string {
  if (error.code === "PGRST202" || error.code === "42883") {
    return "خدمة حفظ اليومية تحتاج تحديثًا من مسؤول النظام. لم يتم حفظ اليومية أو أي مبلغ؛ حاول مجددًا بعد إتمام التحديث.";
  }
  if (error.code === "23505") return "تم تسجيل حضور هذا العامل في هذا اليوم بالفعل. استخدم تصحيح اليومية لتعديل الحضور.";
  if (error.code === "42501") return "حسابك لا يملك صلاحية إتمام هذه اليومية. تسجيل السلفة والمكافأة والخصم يحتاج صلاحية الرواتب.";
  if (error.code === "PGRST301" || error.code === "PGRST302" || error.code === "PGRST303") return "انتهت جلسة الدخول. سجل الدخول مرة أخرى ثم أعد المحاولة.";
  if (error.code === "P0001") {
    if (error.message?.includes("مصروف بالفعل")) return "تم صرف راتب هذا الأسبوع بالفعل. اطلب من المدير مراجعة الصرف قبل تعديل اليومية.";
    const messages: Record<string, string> = {
      "تاريخ غير صالح": "اختر تاريخ يومية صحيحًا؛ لا يمكن تسجيل يومية بتاريخ بعد يوم غد أو قبل سنة 2000.",
      "حالة حضور غير صالحة": "اختر حالة الحضور من القائمة.",
      "نوع الإضافة غير صالح": "اختر نوع إضافة العمل من القائمة.",
      "الإضافة غير صالحة": "راجع قيمة الإضافة؛ لا يمكن احتساب إضافة ليوم غياب.",
      "المبالغ غير صالحة": "راجع المبالغ: يجب أن تكون صفرًا أو أكثر وبحد أقصى منزلتين عشريتين.",
      "العامل غير موجود": "تعذر الوصول للعامل المختار. حدّث الصفحة ثم اختر العامل من جديد.",
    };
    if (error.message && messages[error.message]) return messages[error.message];
  }
  return "تعذر حفظ اليومية. أعد المحاولة، وإذا استمرت المشكلة تواصل مع مسؤول النظام.";
}